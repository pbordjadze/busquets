fn plain(c: char) -> char {
    let c = c.to_ascii_uppercase();
    match c {
        'Á' | 'À' | 'Ä' | 'Â' | 'á' | 'à' | 'ä' | 'â' => 'A',
        'É' | 'È' | 'é' | 'è' | 'ë' => 'E',
        'Í' | 'í' | 'ï' => 'I',
        'Ó' | 'ó' | 'ö' | 'ô' => 'O',
        'Ú' | 'ú' | 'ü' => 'U',
        'Ñ' | 'ñ' => 'N',
        'Ć' | 'ć' | 'Č' | 'č' | 'Ç' | 'ç' => 'C',
        'Š' | 'š' => 'S',
        'Ž' | 'ž' => 'Z',
        'Đ' | 'đ' => 'D',
        _ => c,
    }
}

/// The dots of `text`, in cells (x right, y down; a letter is 5 wide, 7 tall, 6 apart), and its width.
pub fn layout(text: &str) -> (Vec<[f32; 2]>, f32) {
    let mut out = vec![];
    let mut x = 0.0;
    for ch in text.chars() {
        let c = plain(ch);
        if let Some((_, rows)) = GLYPHS.iter().find(|g| g.0 == c) {
            for (j, row) in rows.iter().enumerate() {
                for (i, b) in row.bytes().enumerate() {
                    if b == b'#' {
                        out.push([x + i as f32, j as f32]);
                    }
                }
            }
        }
        x += 6.0;
    }
    (out, (x - 1.0).max(0.0))
}
